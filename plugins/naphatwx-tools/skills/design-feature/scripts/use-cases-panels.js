#!/usr/bin/env node
// Writes every flow's "Use cases (N)" view (4th button + panel) in overview.html from <plan>/use-cases.js, with Play
// links from the mock's play file (no play file → no links). Also removes the old section 07 and "Try in the mock" lines.
// Usage: node use-cases-panels.js <plan-dir> [--use-cases <file>] [--play-file <file>] [--play "<url with {id} {page} {scenario}>"] [--mock <index url>]

const fs = require('fs');
const path = require('path');

const args = process.argv.slice(2);
const opt = (name, d) => { const i = args.indexOf(name); return i >= 0 ? args[i + 1] : d; };
const plan = args[0];
if (!plan) { process.stderr.write('usage: node use-cases-panels.js <plan-dir> [--use-cases <file>] [--play-file <file>] [--play <url>] [--mock <url>]\n'); process.exit(2); }
// A plan made before use cases moved out of the mock keeps them in mock/shared/use-cases.js, play fields included.
const legacy = path.join(plan, 'mock/shared/use-cases.js');
const ucFile = opt('--use-cases', fs.existsSync(path.join(plan, 'use-cases.js')) || !fs.existsSync(legacy) ? path.join(plan, 'use-cases.js') : legacy);
const playFile = opt('--play-file', ucFile === legacy ? legacy : path.join(plan, 'mock/shared/use-case-play.js'));
const play = opt('--play', 'mock/index.html#uc-{id}');
const mockIndex = opt('--mock', 'mock/index.html');
const overviewPath = path.join(plan, 'overview.html');
let html = fs.readFileSync(overviewPath, 'utf8');

/** `<NAME> = [ ... ]` parsed as strict JSON (works for `var X =` and `export const X =`). */
function parseVar(src, name, file) {
    const m = src.match(new RegExp(`\\b${name}\\s*=\\s*\\[`));
    if (!m) throw new Error(`${name} not found in ${file}`);
    const start = m.index + m[0].length - 1;
    let depth = 0, inStr = false;
    for (let j = start; j < src.length; j++) {
        const c = src[j];
        if (inStr) { if (c === '\\') j++; else if (c === '"') inStr = false; continue; }
        if (c === '"') inStr = true;
        else if (c === '[') depth++;
        else if (c === ']' && --depth === 0) return JSON.parse(src.slice(start, j + 1));
    }
    throw new Error(`${name}: unclosed array`);
}
const src = fs.readFileSync(ucFile, 'utf8');
const FLOWS = parseVar(src, 'USE_CASE_FLOWS', ucFile);
const CORE = parseVar(src, 'USE_CASES', ucFile);
// Play entries by id; in the legacy file every use case is its own play entry.
const hasMock = fs.existsSync(playFile);
const PLAY = !hasMock ? [] : playFile === ucFile ? CORE : parseVar(fs.readFileSync(playFile, 'utf8'), 'USE_CASE_PLAY', playFile);
const UCS = CORE.map(u => ({ ...u, ...(PLAY.find(p => p.id === u.id) || { skip: 'no mock' }) }));
const playable = u => hasMock && !u.skip;

const esc = s => String(s).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#x27;' }[c]));
const nn = flow => flow.split('.')[1].padStart(2, '0');
const href = u => play.replace(/\{(id|page|scenario)\}/g, (_, k) => encodeURIComponent(u[k]));
const ext = 'target="_blank" rel="noopener"';
const ucsOf = flow => UCS.filter(u => u.flow === flow);
const playCell = u => playable(u) ? `<a href="${esc(href(u))}" ${ext}>Play ↗</a>` : hasMock ? '<span class="aside">not in the mock</span>' : '';
const plural = n => `${n} use case${n === 1 ? '' : 's'}`;

// ---------------------------------------------------------------- old layout: section 07 and "Try in the mock" lines
// Plans made before use cases moved into the flows: drop section 07 (and the comments above it), renumber Open questions.
html = html.replace(/(?:\n[ \t]*<!--(?:(?!-->)[\s\S])*-->)*\n[ \t]*<section class="slide" id="(?:use-cases|mock)"[\s\S]*?<\/section>\n?/, '');
html = html.replace(/\n[ \t]*<li><a href="#(?:mock|use-cases)">[\s\S]*?<\/li>/, '');
html = html.replace(/(<a href="#open-questions"><span class="n">)08/, '$107')
    .replace(/(<section class="slide" id="open-questions"[^>]*>\s*<h2><span class="sec-n">)08/, '$107')
    .replace(/<!-- =+ 08 OPEN QUESTIONS =+ -->/, '<!-- ============ 07 OPEN QUESTIONS ============ -->');
html = html.replace(/\n[ \t]*<p class="try">[\s\S]*?<\/p>/g, '');

// ---------------------------------------------------------------- "Open the mock" link on the Flows heading
html = html.replace(/(<section class="slide" id="flows"[^>]*>\s*<h2>[\s\S]*?)(?: <a class="side-link"[^>]*>[^<]*<\/a>)?<\/h2>/,
    (_, h2) => `${h2}${hasMock ? ` <a class="side-link" href="${esc(mockIndex)}" ${ext}>Open the mock ↗</a>` : ''}</h2>`);

// ---------------------------------------------------------------- "Use cases" view per flow
const I = '            ';
const panelOf = (f, id) => {
    const ucs = ucsOf(f.flow);
    const open = `<div class="panel" role="region" tabindex="-1" id="${id}" aria-labelledby="${id}-tab" hidden>`;
    const note = `${I}    <!-- Generated by scripts/use-cases-panels.js from use-cases.js${hasMock ? ' and the mock\'s play file' : ''}. Don't hand-edit. -->`;
    if (!ucs.length) return `${open}\n${note}\n${I}    <p class="muted">${esc(f.none || 'No use case for this flow.')}</p>\n${I}</div>`;
    const rows = ucs.map(u => `${I}            <tr><td>${esc(u.title)}<br><span class="aside">${esc(u.expect[0] || '')}</span></td><td class="nowrap">${esc(u.story)}</td>${hasMock ? `<td class="nowrap">${playCell(u)}</td>` : ''}</tr>`);
    return `${open}\n${note}\n${I}    <div class="table-wrap"><table>\n${I}        <thead><tr><th>Use case</th><th>Story</th>${hasMock ? '<th></th>' : ''}</tr></thead><tbody>\n${rows.join('\n')}\n${I}        </tbody></table></div>\n${I}</div>`;
};
const missingFlows = [];
for (const f of FLOWS) {
    const id = `flow-${nn(f.flow)}-uc`;
    const start = html.indexOf(`id="flow-${nn(f.flow)}"`);
    if (start < 0) { missingFlows.push(f.flow); continue; }
    const end = (() => { const e = html.indexOf('</section>', start); return e < 0 ? html.length : e; })();
    let block = html.slice(start, end).replace(/\s*$/, '');
    // the panel is always the block's last child, so cut from it to the end
    const old = block.search(new RegExp(`\\s*<div class="panel"[^>]*id="${id}"`));
    if (old >= 0) block = block.slice(0, old);
    block = block.replace(new RegExp(`\\n[ \\t]*<button[^>]*id="${id}-tab"[^>]*>[^<]*</button>`), '');
    const button = `<button type="button" aria-expanded="false" aria-controls="${id}" id="${id}-tab">Use cases (${ucsOf(f.flow).length})</button>`;
    block = block.replace(/(<div class="views"[\s\S]*?)(\n[ \t]*<\/div>)/, `$1\n${I}    ${button}$2`);
    block += `\n${I}${panelOf(f, id)}\n        `;
    html = html.slice(0, start) + block + html.slice(end);
}

fs.writeFileSync(overviewPath, html);
process.stdout.write(`Use cases written into the flows: ${plural(UCS.length)} in ${FLOWS.length} flows, ${hasMock ? `${UCS.filter(playable).length} playable in the mock` : 'no mock'}\n`);
FLOWS.forEach(f => process.stdout.write(`  ${f.flow} ${f.title}: ${ucsOf(f.flow).length}${hasMock ? ` (${ucsOf(f.flow).filter(playable).length} playable)` : ''}\n`));
if (missingFlows.length) { process.stderr.write(`No #flow-NN block in overview.html for flow(s): ${missingFlows.join(', ')}\n`); process.exit(1); }
